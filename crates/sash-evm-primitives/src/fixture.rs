//! `contracts/src/sash/TinyLlamaFixture.sol`: what it prints ([`FixtureData`]), its rendering
//! ([`render_fixture`]), and its assembly from the 23 segment guests' public values
//! ([`assemble_fixture`], `SPEC.md` §1.1). `make vectors` renders it from `tinyllama_fixture.rs`;
//! `sp1-host fixture-from-bundles` renders it from what the segment guest committed, with the same
//! header, so the two can be compared byte for byte. Also the public values the segment guests must
//! commit on the TinyLlama run ([`tinyllama_segment_public_values`]).

use std::fmt::{self, Write};

use crate::grid::{
    GridError, ModelManifest, SegmentClaim, compute_public_digest, verify_sash_grid,
};
use crate::segment::{SEGMENT_PUBLIC_VALUES_LEN, SegmentPublicValues};
use crate::tinyllama_fixture::{TINYLLAMA_TOK_IN, TINYLLAMA_TOK_OUT, tinyllama_segments};
use crate::token::compute_token_hash;

/// The TinyLlama run's segment count (`SPEC.md` §1.4): `B0L0..B0L21`, then `head`.
pub const FIXTURE_NUM_SEGMENTS: usize = 23;

/// The 23 TinyLlama segments' public values (`SPEC.md` §1.1), in segment order, encoded from
/// `tinyllama_fixture.rs` with [`SegmentPublicValues::encode`]: each claim with its `fixedHash`,
/// `tokenHash(tokIn)` on segment 0, `tokenHash(tokOut)` on `head`, and 32 zero bytes in every other
/// token-hash field. What the segment guest commits on the 23 bundles, and so what each of their
/// proofs and the aggregator's `segmentValues` must carry.
pub fn tinyllama_segment_public_values() -> Vec<[u8; SEGMENT_PUBLIC_VALUES_LEN]> {
    let head = FIXTURE_NUM_SEGMENTS - 1;
    tinyllama_segments()
        .iter()
        .enumerate()
        .map(|(i, c)| {
            SegmentPublicValues {
                segment_index: c.segment_index,
                pre_root: c.pre_root,
                model_root: c.model_root,
                residual_in_root: c.residual_in_root,
                residual_out_root: c.residual_out_root,
                fixed_hash: c.fixed_hash,
                tok_in_hash: if i == 0 {
                    compute_token_hash(&TINYLLAMA_TOK_IN)
                } else {
                    [0; 32]
                },
                tok_out_hash: if i == head {
                    compute_token_hash(&TINYLLAMA_TOK_OUT)
                } else {
                    [0; 32]
                },
            }
            .encode()
        })
        .collect()
}

/// Everything `TinyLlamaFixture.sol` prints. `render_fixture` derives the rest.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FixtureData {
    pub model_id: [u8; 32],
    pub segments: Vec<SegmentClaim>,
    pub eos_token_id: u32,
    pub prompt_ids: Vec<u32>,
    pub answer_ids: Vec<u32>,
    pub tok_in: Vec<u32>,
    pub tok_out: Vec<u32>,
    pub prompt: String,
    pub response: String,
}

/// Renders `TinyLlamaFixture.sol`. `MANIFEST_ROOTS_HASH`, `PUBLIC_DIGEST`, `NUM_SEGMENTS` and
/// `SEQ_LEN = tokIn.len()` come from `grid.rs`. Panics if `tokIn.len()` does not fit a `u16`, which
/// [`assemble_fixture`] rejects.
pub fn render_fixture(data: &FixtureData) -> String {
    let mut out = String::new();
    write_fixture(&mut out, data).expect("writing to a String cannot fail");
    out
}

fn write_fixture(out: &mut String, data: &FixtureData) -> fmt::Result {
    let seq_len = u16::try_from(data.tok_in.len()).expect("SEQ_LEN fits a u16");
    let manifest = ModelManifest::from_segments(&data.segments, seq_len, data.eos_token_id);
    let public_digest =
        compute_public_digest(data.model_id, &data.segments, &data.tok_in, &data.tok_out);

    out.push_str(
        "// Generated by `make vectors` from crates/sash-evm-primitives/src/tinyllama_fixture.rs. Do not edit.\n\
         // SPDX-License-Identifier: Apache-2.0\n\
         pragma solidity ^0.8.38;\n\
         \n\
         import {SashTypes} from \"./SashTypes.sol\";\n\
         \n\
         /// @title TinyLlamaFixture\n\
         /// @notice 23-segment TinyLlama-1.1B-Chat-v1.0 SASH constants (`y-attnout-w12`), taken from an\n\
         ///         unpublished SASH run whose 23 proof bundles regenerate this file byte for byte\n\
         ///         (`make sp1-fixture-check`).\n",
    );
    writeln!(out, "/// @dev Prompt: {:?}", data.prompt)?;
    writeln!(out, "///      Response: {:?}", data.response)?;
    writeln!(out, "library TinyLlamaFixture {{")?;
    writeln!(
        out,
        "    bytes32 internal constant MODEL_ID = {};",
        hex0x(data.model_id)
    )?;
    writeln!(
        out,
        "    bytes32 internal constant MANIFEST_ROOTS_HASH = {};",
        hex0x(manifest.manifest_roots_hash)
    )?;
    writeln!(
        out,
        "    bytes32 internal constant PUBLIC_DIGEST = {};",
        hex0x(public_digest)
    )?;
    writeln!(
        out,
        "    uint16 internal constant NUM_SEGMENTS = {};",
        manifest.num_segments
    )?;
    writeln!(
        out,
        "    uint16 internal constant SEQ_LEN = {};",
        manifest.seq_len
    )?;
    writeln!(
        out,
        "    uint32 internal constant EOS_TOKEN_ID = {};",
        data.eos_token_id
    )?;
    write_u32_array(out, "promptIds", &data.prompt_ids)?;
    write_u32_array(out, "answerIds", &data.answer_ids)?;
    write_u32_array(out, "tokIn", &data.tok_in)?;
    write_u32_array(out, "tokOut", &data.tok_out)?;
    write_segments(out, &data.segments)?;
    writeln!(out, "}}")
}

fn hex0x(bytes: [u8; 32]) -> String {
    format!("0x{}", hex::encode(bytes))
}

fn write_u32_array(out: &mut String, name: &str, values: &[u32]) -> fmt::Result {
    writeln!(out)?;
    writeln!(
        out,
        "    function {name}() internal pure returns (uint32[] memory out) {{"
    )?;
    writeln!(out, "        out = new uint32[]({});", values.len())?;
    for (i, v) in values.iter().enumerate() {
        writeln!(out, "        out[{i}] = {v};")?;
    }
    writeln!(out, "    }}")
}

fn write_segments(out: &mut String, segs: &[SegmentClaim]) -> fmt::Result {
    writeln!(out)?;
    writeln!(
        out,
        "    function segments() internal pure returns (SashTypes.SegmentClaim[] memory segs) {{"
    )?;
    writeln!(
        out,
        "        segs = new SashTypes.SegmentClaim[]({});",
        segs.len()
    )?;
    for (i, s) in segs.iter().enumerate() {
        writeln!(out, "        segs[{i}] = SashTypes.SegmentClaim({{")?;
        writeln!(out, "            segmentIndex: {},", s.segment_index)?;
        writeln!(out, "            preRoot: {},", hex0x(s.pre_root))?;
        writeln!(out, "            modelRoot: {},", hex0x(s.model_root))?;
        writeln!(
            out,
            "            residualInRoot: {},",
            hex0x(s.residual_in_root)
        )?;
        writeln!(
            out,
            "            residualOutRoot: {},",
            hex0x(s.residual_out_root)
        )?;
        writeln!(out, "            fixedHash: {}", hex0x(s.fixed_hash))?;
        writeln!(out, "        }});")?;
    }
    writeln!(out, "    }}")
}

/// Why the segment guests' public values do not assemble into a fixture.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum AssemblyError {
    /// Not exactly [`FIXTURE_NUM_SEGMENTS`] public values.
    SegmentCount { got: usize },
    /// The public values at `position` carry another `segmentIndex`.
    SegmentIndex { position: usize, got: u16 },
    /// Segment 0's `tokInHash` is not `tokenHash(tokIn)`.
    TokInHashMismatch,
    /// The head's `tokOutHash` is not `tokenHash(tokOut)`.
    TokOutHashMismatch,
    /// A segment other than 0 commits a non-zero `tokInHash`.
    UnexpectedTokInHash { segment: usize },
    /// A segment other than the head commits a non-zero `tokOutHash`.
    UnexpectedTokOutHash { segment: usize },
    /// The prompt length is not in `1..=S`.
    PromptLength { prompt_len: usize, seq_len: usize },
    /// `S = tokIn.len()` does not fit a `u16`.
    SequenceLength { got: usize },
    /// The assembled run fails the grid checks (`SPEC.md` §2).
    Grid(GridError),
}

/// The run the segment guests' public values describe, with the enrolled `eosTokenId`: everything
/// in the fixture but what enrollment alone fixes (`modelId`, the prompt and response text).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AssembledRun {
    pub segments: Vec<SegmentClaim>,
    pub eos_token_id: u32,
    pub prompt_ids: Vec<u32>,
    pub answer_ids: Vec<u32>,
    pub tok_in: Vec<u32>,
    pub tok_out: Vec<u32>,
}

impl AssembledRun {
    pub fn into_fixture(self, model_id: [u8; 32], prompt: String, response: String) -> FixtureData {
        FixtureData {
            model_id,
            segments: self.segments,
            eos_token_id: self.eos_token_id,
            prompt_ids: self.prompt_ids,
            answer_ids: self.answer_ids,
            tok_in: self.tok_in,
            tok_out: self.tok_out,
            prompt,
            response,
        }
    }
}

/// Assembles the run from the 23 segments' public values in segment order (`SPEC.md` §1.1) and the
/// token vectors their hashes commit to, and checks it with `verify_sash_grid`. Each claim is the
/// first 162 bytes of its public values, `fixedHash` included. `promptIds = tokIn[0..L]` and
/// `answerIds = tokOut[L-1..S]`, with `L = prompt_len` and `S = tokIn.len()`; the manifest takes
/// `SEQ_LEN = S`, so a `tokOut` of another length fails the grid with `InvalidSequenceLength`.
pub fn assemble_fixture(
    public_values: &[SegmentPublicValues],
    tok_in: &[u32],
    tok_out: &[u32],
    prompt_len: usize,
    eos_token_id: u32,
) -> Result<AssembledRun, AssemblyError> {
    if public_values.len() != FIXTURE_NUM_SEGMENTS {
        return Err(AssemblyError::SegmentCount {
            got: public_values.len(),
        });
    }
    let head = FIXTURE_NUM_SEGMENTS - 1;
    let mut segments = Vec::with_capacity(FIXTURE_NUM_SEGMENTS);
    for (position, v) in public_values.iter().enumerate() {
        if v.segment_index as usize != position {
            return Err(AssemblyError::SegmentIndex {
                position,
                got: v.segment_index,
            });
        }
        if position != 0 && v.tok_in_hash != [0; 32] {
            return Err(AssemblyError::UnexpectedTokInHash { segment: position });
        }
        if position != head && v.tok_out_hash != [0; 32] {
            return Err(AssemblyError::UnexpectedTokOutHash { segment: position });
        }
        segments.push(SegmentClaim {
            segment_index: v.segment_index,
            pre_root: v.pre_root,
            model_root: v.model_root,
            residual_in_root: v.residual_in_root,
            residual_out_root: v.residual_out_root,
            fixed_hash: v.fixed_hash,
        });
    }
    if public_values[0].tok_in_hash != compute_token_hash(tok_in) {
        return Err(AssemblyError::TokInHashMismatch);
    }
    if public_values[head].tok_out_hash != compute_token_hash(tok_out) {
        return Err(AssemblyError::TokOutHashMismatch);
    }

    let s = tok_in.len();
    let seq_len = u16::try_from(s).map_err(|_| AssemblyError::SequenceLength { got: s })?;
    if prompt_len == 0 || prompt_len > s {
        return Err(AssemblyError::PromptLength {
            prompt_len,
            seq_len: s,
        });
    }
    let prompt_ids = tok_in[..prompt_len].to_vec();
    // Empty when `tokOut` is shorter than `S`: the grid's length check comes first and rejects it.
    let answer_ids = tok_out
        .get(prompt_len - 1..s)
        .map(<[u32]>::to_vec)
        .unwrap_or_default();

    let manifest = ModelManifest::from_segments(&segments, seq_len, eos_token_id);
    verify_sash_grid(
        &manifest,
        &segments,
        tok_in,
        tok_out,
        &prompt_ids,
        &answer_ids,
    )
    .map_err(AssemblyError::Grid)?;
    Ok(AssembledRun {
        segments,
        eos_token_id,
        prompt_ids,
        answer_ids,
        tok_in: tok_in.to_vec(),
        tok_out: tok_out.to_vec(),
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::tinyllama_fixture::*;

    /// The committed fixture, generated by `make vectors`.
    const COMMITTED: &str = include_str!("../../../contracts/src/sash/TinyLlamaFixture.sol");

    /// The 23 public values the segment guests commit for the TinyLlama run, decoded.
    fn public_values() -> Vec<SegmentPublicValues> {
        tinyllama_segment_public_values()
            .iter()
            .map(|v| SegmentPublicValues::decode(v).expect("226 bytes"))
            .collect()
    }

    fn assemble(values: &[SegmentPublicValues]) -> Result<AssembledRun, AssemblyError> {
        assemble_fixture(
            values,
            &TINYLLAMA_TOK_IN,
            &TINYLLAMA_TOK_OUT,
            25,
            TINYLLAMA_EOS_TOKEN_ID,
        )
    }

    /// `SPEC.md` §1.1: `tokInHash` on segment 0 and `tokOutHash` on `head`, as §1.4 gives them, and 32
    /// zero bytes in every other token-hash field.
    #[test]
    fn token_hashes_only_on_b0l0_and_head() {
        let values = tinyllama_segment_public_values();
        assert_eq!(values.len(), 23);
        for (i, v) in values.iter().enumerate() {
            let (tok_in_hash, tok_out_hash) =
                (hex::encode(&v[162..194]), hex::encode(&v[194..226]));
            let zero = hex::encode([0; 32]);
            let expected_in = match i {
                0 => "3e683ee8603b85a4f5407e1af5f20a437ddadc9c098acc6aac357d533d3f32cb",
                _ => &zero,
            };
            let expected_out = match i {
                22 => "44c6f339d896d66ea25d0ca6e15214f596ef5c701db79be94232be51d29b6b1e",
                _ => &zero,
            };
            assert_eq!(tok_in_hash, expected_in, "segment {i}");
            assert_eq!(tok_out_hash, expected_out, "segment {i}");
        }
    }

    #[test]
    fn public_values_render_the_committed_fixture() {
        let fixture = assemble(&public_values()).expect("assembles").into_fixture(
            tinyllama_model_id(),
            TINYLLAMA_PROMPT.to_string(),
            TINYLLAMA_RESPONSE.to_string(),
        );
        assert_eq!(fixture.prompt_ids, TINYLLAMA_PROMPT_IDS);
        assert_eq!(fixture.answer_ids, TINYLLAMA_ANSWER_IDS);
        assert_eq!(render_fixture(&fixture), COMMITTED);
    }

    /// Assembly takes each segment's `fixedHash` from its public values: another one renders another
    /// fixture, whose `MANIFEST_ROOTS_HASH` and `PUBLIC_DIGEST` differ from the committed ones.
    #[test]
    fn another_fixed_hash_renders_another_fixture() {
        let mut v = public_values();
        v[22].fixed_hash[31] ^= 0x01;
        let run = assemble(&v).expect("assembles");
        assert_eq!(run.segments[22].fixed_hash, v[22].fixed_hash);
        let rendered = render_fixture(&run.into_fixture(
            tinyllama_model_id(),
            TINYLLAMA_PROMPT.to_string(),
            TINYLLAMA_RESPONSE.to_string(),
        ));
        assert_ne!(rendered, COMMITTED);
    }

    #[test]
    fn tok_in_with_another_hash_fails() {
        let mut tok_in = TINYLLAMA_TOK_IN;
        tok_in[3] += 1;
        assert_eq!(
            assemble_fixture(
                &public_values(),
                &tok_in,
                &TINYLLAMA_TOK_OUT,
                25,
                TINYLLAMA_EOS_TOKEN_ID
            ),
            Err(AssemblyError::TokInHashMismatch)
        );
    }

    #[test]
    fn tok_out_with_another_hash_fails() {
        let mut tok_out = TINYLLAMA_TOK_OUT;
        tok_out[0] += 1;
        assert_eq!(
            assemble_fixture(
                &public_values(),
                &TINYLLAMA_TOK_IN,
                &tok_out,
                25,
                TINYLLAMA_EOS_TOKEN_ID
            ),
            Err(AssemblyError::TokOutHashMismatch)
        );
    }

    #[test]
    fn tok_in_hash_on_a_middle_segment_fails() {
        let mut v = public_values();
        v[11].tok_in_hash = compute_token_hash(&TINYLLAMA_TOK_IN);
        assert_eq!(
            assemble(&v),
            Err(AssemblyError::UnexpectedTokInHash { segment: 11 })
        );
    }

    #[test]
    fn tok_out_hash_outside_the_head_fails() {
        let mut v = public_values();
        v[0].tok_out_hash = compute_token_hash(&TINYLLAMA_TOK_OUT);
        assert_eq!(
            assemble(&v),
            Err(AssemblyError::UnexpectedTokOutHash { segment: 0 })
        );
        let mut v = public_values();
        v[21].tok_out_hash[31] = 1;
        assert_eq!(
            assemble(&v),
            Err(AssemblyError::UnexpectedTokOutHash { segment: 21 })
        );
    }

    #[test]
    fn missing_segment_fails() {
        let mut v = public_values();
        v.remove(5);
        assert_eq!(assemble(&v), Err(AssemblyError::SegmentCount { got: 22 }));
        // The head missing, the last segment duplicated in its place.
        let mut v = public_values();
        v[22] = v[21].clone();
        assert_eq!(
            assemble(&v),
            Err(AssemblyError::SegmentIndex {
                position: 22,
                got: 21
            })
        );
    }

    #[test]
    fn out_of_order_segment_fails() {
        let mut v = public_values();
        v.swap(5, 6);
        assert_eq!(
            assemble(&v),
            Err(AssemblyError::SegmentIndex {
                position: 5,
                got: 6
            })
        );
    }

    #[test]
    fn broken_residual_link_fails_the_grid() {
        let mut v = public_values();
        v[10].residual_out_root[31] ^= 0xff;
        assert_eq!(
            assemble(&v),
            Err(AssemblyError::Grid(GridError::ResidualBoundaryMismatch {
                link: 10
            }))
        );
    }

    /// `SEQ_LEN` is `tokIn.len()`: a `tokOut` of another length, committed by the head, fails the
    /// grid's length check.
    #[test]
    fn tok_out_of_another_length_fails_the_grid() {
        for tok_out in [
            &TINYLLAMA_TOK_OUT[..31],
            &[TINYLLAMA_TOK_OUT, [2; 32]].concat()[..33],
        ] {
            let mut v = public_values();
            v[22].tok_out_hash = compute_token_hash(tok_out);
            assert_eq!(
                assemble_fixture(&v, &TINYLLAMA_TOK_IN, tok_out, 25, TINYLLAMA_EOS_TOKEN_ID),
                Err(AssemblyError::Grid(GridError::InvalidSequenceLength))
            );
        }
    }

    #[test]
    fn prompt_length_outside_the_sequence_fails() {
        for prompt_len in [0, 33] {
            assert_eq!(
                assemble_fixture(
                    &public_values(),
                    &TINYLLAMA_TOK_IN,
                    &TINYLLAMA_TOK_OUT,
                    prompt_len,
                    TINYLLAMA_EOS_TOKEN_ID
                ),
                Err(AssemblyError::PromptLength {
                    prompt_len,
                    seq_len: 32
                })
            );
        }
    }
}
