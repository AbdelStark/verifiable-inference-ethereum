//! Deterministically generates the Solidity TinyLlama-1.1B 23-segment fixture library for Foundry.

use std::env;
use std::fmt::{self, Write};
use std::fs;
use std::path::PathBuf;

use sha2::{Digest, Sha256};

use sash_evm_primitives::grid::{SegmentClaim, compute_public_digest};
use sash_evm_primitives::tinyllama_fixture::{
    TINYLLAMA_ANSWER_IDS, TINYLLAMA_B0_REL_DRAWS, TINYLLAMA_EOS_TOKEN_ID, TINYLLAMA_HEAD_REL_DRAWS,
    TINYLLAMA_PROMPT, TINYLLAMA_PROMPT_IDS, TINYLLAMA_RESPONSE, TINYLLAMA_TOK_IN,
    TINYLLAMA_TOK_OUT, tinyllama_manifest, tinyllama_segments,
};

fn hex0x(bytes: [u8; 32]) -> String {
    format!("0x{}", hex::encode(bytes))
}

fn write_u32_array(out: &mut String, name: &str, values: &[u32]) -> fmt::Result {
    writeln!(out)?;
    writeln!(
        out,
        "    function {name}() internal pure returns (uint32[] memory out) {{"
    )?;
    writeln!(out, "        out = new uint32[]({});", values.len())?;
    for (i, v) in values.iter().enumerate() {
        writeln!(out, "        out[{i}] = {v};")?;
    }
    writeln!(out, "    }}")
}

fn write_segments(out: &mut String, segs: &[SegmentClaim]) -> fmt::Result {
    writeln!(out)?;
    writeln!(
        out,
        "    function segments() internal pure returns (SashTypes.SegmentClaim[] memory segs) {{"
    )?;
    writeln!(
        out,
        "        segs = new SashTypes.SegmentClaim[]({});",
        segs.len()
    )?;
    for (i, s) in segs.iter().enumerate() {
        let [a0, a1, b0, b1] = s.token_horner_claim.to_u32_array();
        writeln!(out, "        segs[{i}] = SashTypes.SegmentClaim({{")?;
        writeln!(out, "            segmentIndex: {},", s.segment_index)?;
        writeln!(out, "            relationDraws: {},", s.relation_draws)?;
        writeln!(out, "            preRoot: {},", hex0x(s.pre_root))?;
        writeln!(out, "            modelRoot: {},", hex0x(s.model_root))?;
        writeln!(out, "            traceRoot: {},", hex0x(s.trace_root))?;
        writeln!(
            out,
            "            residualInRoot: {},",
            hex0x(s.residual_in_root)
        )?;
        writeln!(
            out,
            "            residualOutRoot: {},",
            hex0x(s.residual_out_root)
        )?;
        writeln!(
            out,
            "            tokenHornerClaim: QM31.Elem({a0}, {a1}, {b0}, {b1})"
        )?;
        writeln!(out, "        }});")?;
    }
    writeln!(out, "    }}")
}

fn render() -> Result<String, fmt::Error> {
    let model_id: [u8; 32] =
        Sha256::digest(b"TinyLlama/TinyLlama-1.1B-Chat-v1.0@fe8a4ea1ffedaf415f4da2f062534de366a451e6:y-attnout-w12").into();
    let manifest = tinyllama_manifest();
    let segs = tinyllama_segments();
    let public_digest = compute_public_digest(model_id, &segs);

    let mut out = String::new();
    out.push_str(
        "// Generated by `make vectors` from crates/sash-evm-primitives/src/tinyllama_fixture.rs. Do not edit.\n\
         // SPDX-License-Identifier: Apache-2.0\n\
         pragma solidity ^0.8.38;\n\
         \n\
         import {QM31} from \"../field/QM31.sol\";\n\
         import {SashTypes} from \"./SashTypes.sol\";\n\
         \n\
         /// @title TinyLlamaFixture\n\
         /// @notice Primary-source 23-segment TinyLlama-1.1B-Chat-v1.0 SASH proof constants (`y-attnout-w12`).\n",
    );
    writeln!(out, "/// @dev Prompt: {TINYLLAMA_PROMPT:?}")?;
    writeln!(out, "///      Response: {TINYLLAMA_RESPONSE:?}")?;
    writeln!(out, "library TinyLlamaFixture {{")?;
    writeln!(
        out,
        "    bytes32 internal constant MODEL_ID = {};",
        hex0x(model_id)
    )?;
    writeln!(
        out,
        "    bytes32 internal constant MANIFEST_ROOTS_HASH = {};",
        hex0x(manifest.manifest_roots_hash)
    )?;
    writeln!(
        out,
        "    bytes32 internal constant PUBLIC_DIGEST = {};",
        hex0x(public_digest)
    )?;
    writeln!(
        out,
        "    uint16 internal constant NUM_SEGMENTS = {};",
        manifest.num_segments
    )?;
    writeln!(
        out,
        "    uint16 internal constant SEQ_LEN = {};",
        manifest.seq_len
    )?;
    writeln!(
        out,
        "    uint32 internal constant EOS_TOKEN_ID = {TINYLLAMA_EOS_TOKEN_ID};"
    )?;
    writeln!(
        out,
        "    uint16 internal constant B0_REL_DRAWS = {TINYLLAMA_B0_REL_DRAWS};"
    )?;
    writeln!(
        out,
        "    uint16 internal constant HEAD_REL_DRAWS = {TINYLLAMA_HEAD_REL_DRAWS};"
    )?;
    write_u32_array(&mut out, "promptIds", &TINYLLAMA_PROMPT_IDS)?;
    write_u32_array(&mut out, "answerIds", &TINYLLAMA_ANSWER_IDS)?;
    write_u32_array(&mut out, "tokIn", &TINYLLAMA_TOK_IN)?;
    write_u32_array(&mut out, "tokOut", &TINYLLAMA_TOK_OUT)?;
    write_segments(&mut out, &segs)?;
    writeln!(out, "}}")?;
    Ok(out)
}

fn main() {
    let out_path = env::args()
        .nth(1)
        .map(PathBuf::from)
        .unwrap_or_else(|| PathBuf::from("contracts/src/sash/TinyLlamaFixture.sol"));
    let rendered = render().expect("render Solidity fixture");
    fs::write(&out_path, rendered).expect("write Solidity fixture");
}
