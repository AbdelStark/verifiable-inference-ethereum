//! `sp1-host fixture-from-bundles` (#44): it never writes under the checkout's `contracts/src`, and on
//! the 23 TinyLlama public values beside a corpus statement carrying the TinyLlama tokens it renders
//! the committed `TinyLlamaFixture.sol` byte for byte. The second test needs the synthetic corpus:
//! `SASH_SYNTHETIC_CORPUS=<dir> cargo test --release --locked -p sp1-host --test fixture -- --ignored`
//! (`make sp1-guest-suite`, and the `sp1` or `sp1-cached` CI job).

#[path = "../../sash-segment-check/tests/common/mod.rs"]
mod common;

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

use sash_evm_primitives::fixture::tinyllama_segment_public_values;
use sash_evm_primitives::tinyllama_fixture::{TINYLLAMA_TOK_IN, TINYLLAMA_TOK_OUT};
use serde_json::{Value, json};
use sp1_host::pins::repo_root;
use sp1_host::tinyllama_tags;

/// The committed fixture, generated by `make vectors`.
fn committed_fixture() -> PathBuf {
    repo_root().join("contracts/src/sash/TinyLlamaFixture.sol")
}

/// A fresh empty directory under the system's temp directory, outside the checkout.
fn temp_dir(name: &str) -> PathBuf {
    let dir = std::env::temp_dir().join(format!("sp1-host-fixture-{name}-{}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    dir.canonicalize().unwrap()
}

/// `sp1-host fixture-from-bundles` run from `cwd`, with both input directories `inputs`.
fn fixture_from_bundles(cwd: &Path, inputs: &Path, out: &Path) -> Output {
    Command::new(env!("CARGO_BIN_EXE_sp1-host"))
        .current_dir(cwd)
        .arg("fixture-from-bundles")
        .arg("--public-values")
        .arg(inputs)
        .arg("--bundles")
        .arg(inputs)
        .args(["--prompt-len", "25"])
        .arg("--out")
        .arg(out)
        .output()
        .unwrap()
}

#[test]
fn out_under_contracts_src_is_refused() {
    let root = repo_root().canonicalize().unwrap();
    let before = fs::read(committed_fixture()).unwrap();
    let inputs = temp_dir("refused");
    std::os::unix::fs::symlink(committed_fixture(), inputs.join("link.sol")).unwrap();
    let dangling = root.join("contracts/src/dangling.sol");
    assert!(!dangling.exists());
    std::os::unix::fs::symlink(&dangling, inputs.join("dangling.sol")).unwrap();
    for (cwd, out) in [
        (root.clone(), "contracts/src/sash/TinyLlamaFixture.sol"),
        (
            root.join("sp1"),
            "../contracts/src/sash/TinyLlamaFixture.sol",
        ),
        (root.join("sp1"), "../sp1/../contracts/src/fixture.sol"),
        // A symlink outside the checkout to the committed fixture.
        (inputs.clone(), "link.sol"),
        // A dangling symlink outside the checkout to a new file under `contracts/src`.
        (inputs.clone(), "dangling.sol"),
    ] {
        let output = fixture_from_bundles(&cwd, &inputs, Path::new(out));
        let stderr = String::from_utf8_lossy(&output.stderr);
        assert_eq!(output.status.code(), Some(2), "{out}: {stderr}");
        assert!(
            stderr.contains("the committed fixture changes only through `make vectors`"),
            "{out}: {stderr}"
        );
    }
    assert_eq!(fs::read(committed_fixture()).unwrap(), before);
    assert!(!root.join("contracts/src/fixture.sol").exists());
    assert!(!dangling.exists());
    fs::remove_dir_all(inputs).unwrap();
}

#[test]
#[ignore = "needs the synthetic corpus in SASH_SYNTHETIC_CORPUS (sp1 or sp1-cached CI job)"]
fn corpus_statement_and_tinyllama_public_values_render_the_committed_fixture() {
    let mut fixed: Value = serde_json::from_slice(
        &fs::read(common::corpus().join("sound_aligned.fixed.json")).unwrap(),
    )
    .unwrap();
    fixed["tok_in"] = json!(TINYLLAMA_TOK_IN);
    fixed["tok_out"] = json!(TINYLLAMA_TOK_OUT);
    let fixed = serde_json::to_vec(&fixed).unwrap();

    let dir = temp_dir("corpus");
    fs::write(dir.join("B0L0.fixed.json"), &fixed).unwrap();
    fs::write(dir.join("head.fixed.json"), &fixed).unwrap();
    for (tag, values) in tinyllama_tags()
        .iter()
        .zip(tinyllama_segment_public_values())
    {
        fs::write(dir.join(format!("{tag}.public-values")), values).unwrap();
    }
    let out = dir.join("TinyLlamaFixture.sol");
    let output = fixture_from_bundles(&dir, &dir, &out);
    assert!(
        output.status.success(),
        "stderr: {}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(
        fs::read(&out).unwrap() == fs::read(committed_fixture()).unwrap(),
        "{} differs from contracts/src/sash/TinyLlamaFixture.sol",
        out.display()
    );
    fs::remove_dir_all(dir).unwrap();
}
